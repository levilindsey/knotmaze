// K1247 WASM: build outline_rec.ts, a recording copy of ../proto/outline.ts.
// footNearM, footWinFast and marginOfC get wrappers that, while
// globalThis.__wrec.on is set, log each call's inputs and answers (see
// record.ts). The kernels themselves are untouched (renamed *_orig).
//   node .claude/probes/K1240/wasm/make_rec.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const here = dirname(fileURLToPath(import.meta.url));
const srcPath = join(here, "..", "proto", "outline.ts");
let src = readFileSync(srcPath, "utf8");
const sha = createHash("sha256").update(src).digest("hex").slice(0, 12);

function rename(sig, to) {
  const n = src.split(sig).length - 1;
  if (n !== 1) throw new Error(`expected one '${sig}', found ${n}`);
  src = src.replace(sig, to);
}
rename("function footNearM(C: FCache, arm: FArm, out: FFoot): void {", "function footNearM_orig(C: FCache, arm: FArm, out: FFoot): void {");
rename("function footWinFast(p: Poly, out: FFoot): void {", "function footWinFast_orig(p: Poly, out: FFoot): void {");
rename("function marginOfC(C: FCache, ai: number, ft: FFoot, cache: WalkCache): number {", "function marginOfC_orig(C: FCache, ai: number, ft: FFoot, cache: WalkCache): number {");

src += `
// ---- K1247 WASM recorder (generated by wasm/make_rec.mjs) ----
type WRec = { on: boolean; C: FCache | null; fnm: number[]; fwf: number[]; moc: number[]; polys: Map<number, Poly>; tans: Map<number, Float64Array[]> };
function wrec(): WRec | null { const R = (globalThis as unknown as { __wrec?: WRec }).__wrec; return R && R.on ? R : null; }
function snapPoly(p: Poly): Poly {
  return { id: p.id, n: p.n, closed: p.closed, nseg: p.nseg, len: p.len, s0: p.s0, nblk: p.nblk,
    x: p.x.slice(), y: p.y.slice(), s: p.s.slice(), segLen: p.segLen.slice(), dx: p.dx.slice(), dy: p.dy.slice(),
    bx0: p.bx0.slice(), by0: p.by0.slice(), bx1: p.bx1.slice(), by1: p.by1.slice(), bk: p.bk.slice() };
}
function notePoly(R: WRec, C: FCache, pi: number): void { R.C = C; if (!R.polys.has(pi)) R.polys.set(pi, snapPoly(C.polys[pi])); }
function walkFields(c: WalkCache): number[] { return [c.valid ? 1 : 0, c.qx, c.qy, c.footStartS, c.footEndS, c.hiS, c.kHi, c.bkHi, c.minF, c.loS, c.kLo, c.bkLo, c.maxB, c.oLo, c.oHi]; }
function footNearM(C: FCache, arm: FArm, out: FFoot): void {
  const R = wrec();
  if (!R) { footNearM_orig(C, arm, out); return; }
  notePoly(R, C, arm.pi);
  const rec = [arm.pi, arm.dir, arm.sR, arm.L, kfXY[0], kfXY[1], out.u, out.k];
  footNearM_orig(C, arm, out);
  R.fnm.push(...rec, out.d, out.x, out.y, out.s, out.k, out.u);
}
function footWinFast(p: Poly, out: FFoot): void {
  const R = wrec();
  if (!R || !R.C) { footWinFast_orig(p, out); return; }
  const pi = R.C.polys.indexOf(p);
  if (pi < 0) throw new Error("footWinFast on a poly outside C.polys");
  notePoly(R, R.C, pi);
  const rec = [pi, fwA[0], fwA[1], fwA[2], fwA[3], fwA[4], fwA[5], fwA[6], fwA[7], fwA[8]];
  footWinFast_orig(p, out);
  R.fwf.push(...rec, out.d, out.x, out.y, out.s, out.k, out.u);
}
function marginOfC(C: FCache, ai: number, ft: FFoot, cache: WalkCache): number {
  const R = wrec();
  if (!R) return marginOfC_orig(C, ai, ft, cache);
  const pi = C.armObj[ai].pi;
  notePoly(R, C, pi);
  if (!R.tans.has(pi)) R.tans.set(pi, [C.tanTx[pi].slice(), C.tanTy[pi].slice(), C.tanGF[pi].slice(), C.tanGB[pi].slice()]);
  const rec = [pi, C.armDir[ai], C.armSR[ai], C.armL[ai], kfCst.qx, kfCst.qy, ft.u, ft.d, ft.k, ...walkFields(cache)];
  const r = marginOfC_orig(C, ai, ft, cache);
  R.moc.push(...rec, r, ...walkFields(cache));
  return r;
}
export const __recSourceSha = ${JSON.stringify(sha)};
export function __recH(): number { const R = (globalThis as unknown as { __wrec?: WRec }).__wrec; return R && R.C ? R.C.h : NaN; }
`;
writeFileSync(join(here, "outline_rec.ts"), src);
console.log(`wrote outline_rec.ts from outline.ts sha ${sha}`);
