// K1247 WASM: build kernels_js.ts, the JS side of the comparison: normS,
// segOfS, footNearM, fwScan, footWinFast and marginOfC copied VERBATIM from
// ../proto/outline.ts (each from `function NAME(` to the next column-0 `}`),
// under a minimal header standing in for FCache, FArm, kfCst and friends.
//   node .claude/probes/K1240/wasm/make_js.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const here = dirname(fileURLToPath(import.meta.url));
const raw = readFileSync(join(here, "..", "proto", "outline.ts"), "utf8");
const sha = createHash("sha256").update(raw).digest("hex").slice(0, 12);
const src = raw.replace(/\r\n/g, "\n");
function fn(name) {
  const re = new RegExp(`\\nfunction ${name}\\(`);
  const m = re.exec(src);
  if (!m) throw new Error(`no function ${name}`);
  const end = src.indexOf("\n}\n", m.index + 1);
  return src.slice(m.index + 1, end + 2);
}
const header = `// GENERATED by make_js.mjs from ../proto/outline.ts (sha ${sha}); do not edit.
// The kernels below are verbatim; the header stands in for outline.ts's types.
/* eslint-disable */
export interface Poly {
  id: number; n: number; closed: boolean; nseg: number; len: number; s0: number;
  x: Float64Array; y: Float64Array; s: Float64Array; segLen: Float64Array; dx: Float64Array; dy: Float64Array;
  bx0: Float64Array; by0: Float64Array; bx1: Float64Array; by1: Float64Array;
  bk: Float64Array; nblk: number;
}
export interface FArm { pi: number; dir: number; sR: number; L: number }
export interface FFoot { d: number; x: number; y: number; s: number; k: number; u: number }
export interface WalkCache { valid: boolean; qx: number; qy: number; footStartS: number; footEndS: number; hiS: number; kHi: number; bkHi: number; minF: number; loS: number; kLo: number; bkLo: number; maxB: number; oLo: number; oHi: number }
export interface FCache {
  h: number; polys: Poly[]; armObj: FArm[]; armSR: Float64Array; armDir: Int32Array; armL: Float64Array;
  tanTx: Float64Array[]; tanTy: Float64Array[]; tanGF: Float64Array[]; tanGB: Float64Array[];
}
export const kfXY = new Float64Array(2);
export const kfCst = { qx: 0, qy: 0 };
const kfMFoot: FFoot = { d: 0, x: 0, y: 0, s: 0, k: 0, u: 0 };
export const JS_SOURCE_SHA = ${JSON.stringify(sha)};
`;
const fwDecl = /\nconst fwS = new Float64Array\(11\); const fwA = new Float64Array\(9\);\n/;
if (!fwDecl.test(src)) throw new Error("fwS/fwA declaration changed");
const body = [
  fn("normS"), fn("segOfS"),
  "export const fwS = new Float64Array(11); export const fwA = new Float64Array(9);\n",
  fn("fwScan"), fn("footWinFast"), fn("footNearM"), fn("marginOfC"),
].join("\n");
writeFileSync(join(here, "kernels_js.ts"), header + "\n" + body + "\nexport { footNearM, footWinFast, marginOfC, normS };\n");
console.log(`wrote kernels_js.ts from outline.ts sha ${sha}`);
