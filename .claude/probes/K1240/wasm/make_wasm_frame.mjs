// K1247 WASM: build outline_wasm.ts, a copy of ../proto/outline.ts whose
// footNearM and marginOfC can run in build/kernels.wasm inside the real
// frame (the partial port: everything else stays JS). Off by default; the
// two builds: outline_wasm.ts (on) and outline_wasm_off.ts (off, the same
// copy's JS baseline). The driver (frame_wasm.ts) hands __wasmSet the
// instance and marks each frame
// with __wasmDirty, and the first kernel call of a frame copies every
// polyline and tangent table into WASM memory (setupFrame has rebuilt them).
// marginOfC's WalkCache stays a JS object, copied in and out per call.
//   node .claude/probes/K1240/wasm/make_wasm_frame.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const here = dirname(fileURLToPath(import.meta.url));
let src = readFileSync(join(here, "..", "proto", "outline.ts"), "utf8");
const sha = createHash("sha256").update(src).digest("hex").slice(0, 12);
function rename(sig, to) {
  const n = src.split(sig).length - 1;
  if (n !== 1) throw new Error(`expected one '${sig}', found ${n}`);
  src = src.replace(sig, to);
}
rename("function footNearM(C: FCache, arm: FArm, out: FFoot): void {", "function footNearM_js(C: FCache, arm: FArm, out: FFoot): void {");
rename("function marginOfC(C: FCache, ai: number, ft: FFoot, cache: WalkCache): number {", "function marginOfC_js(C: FCache, ai: number, ft: FFoot, cache: WalkCache): number {");

src += `
// ---- K1247 WASM partial port (generated by wasm/make_wasm_frame.mjs) ----
type WEx = {
  memory: WebAssembly.Memory; heapBase(): number; setup(hdr: number, out: number, mfoot: number, cache: number, h: number): void;
  fnm(pi: number, dir: number, sR: number, L: number, x: number, y: number, hs: number, hk: number): void;
  moc(pi: number, dir: number, sR: number, L: number, x: number, y: number, u: number, d: number, k: number): number;
};
const wOn = __W_ON__; let wDirty = true; let wEx: WEx | null = null;
let wM = new Float64Array(0); let wMI = new Int32Array(0);
let wOut = 0; let wCache = 0; let wHdr = 0; let wData = 0;
export const __wasmSourceSha = ${JSON.stringify(sha)};
export function __wasmSet(on: boolean, ex?: WEx): void {
  if (ex && ex !== wEx) {
    wEx = ex;
    const base = Math.max(1024, (ex.heapBase() + 15) & ~15);
    const OUT = base; const MFOOT = base + 64; const CACHE = base + 128; wHdr = base + 256;
    wOut = OUT >> 3; wCache = CACHE >> 3; wData = wHdr + 256 * 128;
    if (ex.memory.buffer.byteLength < wData + 65536) ex.memory.grow(Math.ceil((wData + 65536 - ex.memory.buffer.byteLength) / 65536));
    wM = new Float64Array(ex.memory.buffer); wMI = new Int32Array(ex.memory.buffer);
    ex.setup(wHdr, OUT, MFOOT, CACHE, 0);
  }
  if (on !== wOn) throw new Error("this build has WASM " + (wOn ? "on" : "off"));
  wDirty = true;
}
export function __wasmDirty(): void { wDirty = true; }
function wSync(C: FCache): void {
  const ex = wEx as WEx;
  if (C.polys.length > 256) throw new Error("wasm header table holds 256 polys");
  let need = wData;
  for (let pi = 0; pi < C.polys.length; pi++) { const p = C.polys[pi]; need += 8 * (3 * p.n + 7 * p.nseg + 4 * p.nblk + 4 * (p.n + 1)) + 16 * 16; }
  if (need > ex.memory.buffer.byteLength) { ex.memory.grow(Math.ceil((need - ex.memory.buffer.byteLength) / 65536)); wM = new Float64Array(ex.memory.buffer); wMI = new Int32Array(ex.memory.buffer); }
  const M = wM; const MI = wMI;
  let at = wData;
  const put = (a: Float64Array, len: number): number => { const o = at; if (len > 0) M.set(len === a.length ? a : a.subarray(0, len), o >> 3); at = (at + 8 * len + 15) & ~15; return o; };
  for (let pi = 0; pi < C.polys.length; pi++) {
    const p = C.polys[pi]; const hb = wHdr + pi * 128; const hi = hb >> 2;
    MI[hi] = p.n; MI[hi + 1] = p.nseg; MI[hi + 2] = p.closed ? 1 : 0; MI[hi + 3] = p.nblk;
    M[(hb + 16) >> 3] = p.len; M[(hb + 24) >> 3] = p.s0;
    MI[hi + 8] = put(p.x, p.n); MI[hi + 9] = put(p.y, p.n); MI[hi + 10] = put(p.s, p.n);
    MI[hi + 11] = put(p.segLen, p.nseg); MI[hi + 12] = put(p.dx, p.nseg); MI[hi + 13] = put(p.dy, p.nseg);
    MI[hi + 14] = put(p.bx0, p.nseg); MI[hi + 15] = put(p.by0, p.nseg); MI[hi + 16] = put(p.bx1, p.nseg); MI[hi + 17] = put(p.by1, p.nseg);
    MI[hi + 18] = put(p.bk, 4 * p.nblk);
    if (C.armsOfChain[pi].length) {
      MI[hi + 19] = put(C.tanTx[pi], p.nseg); MI[hi + 20] = put(C.tanTy[pi], p.nseg);
      MI[hi + 21] = put(C.tanGF[pi], p.nseg); MI[hi + 22] = put(C.tanGB[pi], p.n);
    }
  }
  ex.setup(wHdr, wOut << 3, (wOut << 3) + 64, wCache << 3, C.h);
  wDirty = false;
}
function footNearM(C: FCache, arm: FArm, out: FFoot): void {
  if (!wOn) { footNearM_js(C, arm, out); return; }
  if (wDirty) wSync(C);
  (wEx as WEx).fnm(arm.pi, arm.dir, arm.sR, arm.L, kfXY[0], kfXY[1], out.u, out.k);
  const M = wM; const o = wOut;
  out.d = M[o]; out.x = M[o + 1]; out.y = M[o + 2]; out.s = M[o + 3]; out.k = M[o + 4]; out.u = M[o + 5];
}
function marginOfC(C: FCache, ai: number, ft: FFoot, cache: WalkCache): number {
  if (!wOn) return marginOfC_js(C, ai, ft, cache);
  if (wDirty) wSync(C);
  const M = wM; const c = wCache;
  M[c] = cache.valid ? 1 : 0; M[c + 1] = cache.qx; M[c + 2] = cache.qy; M[c + 3] = cache.footStartS; M[c + 4] = cache.footEndS;
  M[c + 5] = cache.hiS; M[c + 6] = cache.kHi; M[c + 7] = cache.bkHi; M[c + 8] = cache.minF; M[c + 9] = cache.loS; M[c + 10] = cache.kLo;
  M[c + 11] = cache.bkLo; M[c + 12] = cache.maxB; M[c + 13] = cache.oLo; M[c + 14] = cache.oHi;
  const r = (wEx as WEx).moc(C.armObj[ai].pi, C.armDir[ai], C.armSR[ai], C.armL[ai], kfCst.qx, kfCst.qy, ft.u, ft.d, ft.k);
  cache.valid = M[c] !== 0; cache.qx = M[c + 1]; cache.qy = M[c + 2]; cache.footStartS = M[c + 3]; cache.footEndS = M[c + 4];
  cache.hiS = M[c + 5]; cache.kHi = M[c + 6]; cache.bkHi = M[c + 7]; cache.minF = M[c + 8]; cache.loS = M[c + 9]; cache.kLo = M[c + 10];
  cache.bkLo = M[c + 11]; cache.maxB = M[c + 12]; cache.oLo = M[c + 13]; cache.oHi = M[c + 14];
  return r;
}
`;
writeFileSync(join(here, "outline_wasm.ts"), src.replace("__W_ON__", "true"));
writeFileSync(join(here, "outline_wasm_off.ts"), src.replace("__W_ON__", "false"));
console.log(`wrote outline_wasm.ts (WASM on) and outline_wasm_off.ts (the same copy, WASM off) from outline.ts sha ${sha}`);
