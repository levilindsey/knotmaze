// K115 offline generator: Hershey Script Simplex (.jhf) -> src/core/hershey_script.ts
// Usage: node .claude/probes/K115/gen_data.mjs
// Parses .claude/probes/K115/data/scripts.jhf (the kamalmostafa/hershey-fonts
// distribution of Dr. A. V. Hershey's data, format by James Hurt) and emits
// integer stroke data for ASCII 32-126. No .jhf parsing ships at runtime.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, "data", "scripts.jhf");
const out = path.resolve(here, "..", "..", "..", "src", "core", "hershey_script.ts");

function parseJhf(file) {
  const lines = fs.readFileSync(file, "utf8").replace(/\r/g, "").split("\n");
  const glyphs = [];
  let i = 0;
  while (i < lines.length) {
    const line = lines[i++];
    if (!line.trim()) continue;
    const n = parseInt(line.slice(5, 8), 10);
    let data = line.slice(8);
    while (data.length < 2 * n && i < lines.length) data += lines[i++];
    const R = "R".charCodeAt(0);
    const left = data.charCodeAt(0) - R;
    const right = data.charCodeAt(1) - R;
    const strokes = [];
    let cur = [];
    for (let k = 1; k < n; k++) {
      const a = data[2 * k];
      const b = data[2 * k + 1];
      if (a === " " && b === "R") {
        if (cur.length) strokes.push(cur);
        cur = [];
        continue;
      }
      cur.push([a.charCodeAt(0) - R, b.charCodeAt(0) - R]);
    }
    if (cur.length) strokes.push(cur);
    glyphs.push({ left, right, strokes });
  }
  return glyphs;
}

const all = parseJhf(src);
if (all.length < 95) throw new Error(`expected at least 95 glyphs, got ${all.length}`);
const glyphs = all.slice(0, 95); // ASCII 32..126

const fmtPt = (p) => `[${p[0]},${p[1]}]`;
const fmtStroke = (s) => `[${s.map(fmtPt).join(",")}]`;
const lines = [];
lines.push("// K115: Hershey Script Simplex stroke data (ASCII 32-126), integers in");
lines.push("// Hershey units (x-height 9, baseline y=9, join line y=4, y grows down).");
lines.push("//");
lines.push("// Source: Dr. A. V. Hershey's single-line fonts (U.S. National Bureau of");
lines.push("// Standards), in the .jhf format created by James Hurt (Cognition, Inc.);");
lines.push("// file data/scripts.jhf of the kamalmostafa/hershey-fonts distribution.");
lines.push("// The Hershey licence permits any use provided those acknowledgements");
lines.push("// ship with the data (see the hershey-fonts credit in notices/credits.ts).");
lines.push("//");
lines.push("// GENERATED by .claude/probes/K115/gen_data.mjs from");
lines.push("// .claude/probes/K115/data/scripts.jhf -- do not edit by hand.");
lines.push("");
lines.push("export interface HersheyGlyph {");
lines.push("  left: number; // Advance origin offset (glyph x = cursor - left).");
lines.push("  right: number;");
lines.push("  strokes: ReadonlyArray<ReadonlyArray<readonly [number, number]>>;");
lines.push("}");
lines.push("");
lines.push("// Index = char code - 32 (ASCII 32-126).");
lines.push("export const HERSHEY_SCRIPT: readonly HersheyGlyph[] = [");
for (let i = 0; i < glyphs.length; i++) {
  const g = glyphs[i];
  const ch = String.fromCharCode(32 + i);
  const label = ch === "\\" ? "\\\\" : ch === '"' ? '\\"' : ch;
  lines.push(
    `  { left: ${g.left}, right: ${g.right}, strokes: [${g.strokes.map(fmtStroke).join(",")}] }, // ${32 + i} ${JSON.stringify(label)}`
  );
}
lines.push("];");
lines.push("");
fs.writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out}: ${glyphs.length} glyphs`);
